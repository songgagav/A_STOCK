def table(header, rows):
    """构造 markdown 表格(避免手写长行引号)。"""
    out = ["| " + " | ".join(header) + " |",
           "|" + "---|" * len(header)]
    for r in rows:
        out.append("| " + " | ".join(str(x) for x in r) + " |")
    return NL.join(out)


